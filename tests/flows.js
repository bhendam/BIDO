  await p.click('.pick[data-name="toId"] .pchip[data-pv]:not([data-pv=""])');
  await p.fill('form[data-form="box"] input[name="count"]','10');
  await p.click('form[data-form="box"] [data-act="saveAgain"]');await dlg();await p.waitForTimeout(500);
